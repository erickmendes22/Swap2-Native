#!/usr/bin/env python3
"""Embed reviewed vegetation shader keys from game profiles; no pack rebuild."""
from pathlib import Path
import argparse
ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'dm/gfx/vk_android/vka_vegetation_profiles.h'
def render():
    rows = []
    for profile in sorted((ROOT / 'dm/games').glob('*/game.tsv')):
        keys = []
        for line in profile.read_text().splitlines():
            cells = line.split('\t')
            if cells[0] != 'mesh_vegetation_cut':
                continue
            assert len(cells) == 3 and cells[1] != cells[2], line
            for key in cells[1:]:
                assert len(key) == 16 and int(key, 16), key
                assert key not in keys, key
                keys.append(key)
        rows += [f'    {{"{profile.parent.name}", UINT64_C(0x{key})}},' for key in keys]
    return '\n'.join(['// Generated by mesh_vegetation_profile.py from game.tsv; reviewed pairs from Banana Native.',
        '#pragma once', '#include <stdint.h>', '#include <string.h>',
        'static int vka_vegetation_key(const char *title, uint64_t key) {',
        '    static const struct { const char *title; uint64_t key; } entries[] = {', *rows,
        '    };', '    for (unsigned i = 0; title && i < sizeof entries / sizeof *entries; i++)',
        '        if (key == entries[i].key && !strcmp(title, entries[i].title)) return 1;',
        '    return 0;', '}', ''])
if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); args = ap.parse_args()
    result = render()
    if args.check:
        assert OUT.read_text() == result, 'Regenerate vegetation profile header'
    else:
        OUT.write_text(result)
