#!/usr/bin/env python3
"""Build the small runtime visibility helper; external shader libraries are unchanged."""
from pathlib import Path
import hashlib
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'dm/gfx/vk_android/rc/visibility.comp'
HEADER = ROOT / 'dm/gfx/vk_android/vka_rc_gpu_spv.h'

if __name__ == '__main__':
    with tempfile.TemporaryDirectory() as tmp:
        output = Path(tmp) / 'visibility.spv'
        subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.1',
                        str(SOURCE), '-o', str(output)], check=True)
        subprocess.run(['spirv-val', '--target-env', 'vulkan1.1', str(output)], check=True)
        words = struct.unpack('<' + 'I' * (output.stat().st_size // 4), output.read_bytes())
        digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
        rows = [', '.join(f'0x{x:08x}' for x in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
        HEADER.write_text('// Generated by dm/gfx/tools/rc_gpu_spv.py; source SHA256 ' + digest + '\n'
                          '#pragma once\n#include <stdint.h>\n'
                          f'static const uint32_t SPV_RC_VISIBILITY[{len(words)}] = {{\n' + '\n'.join(rows) + '\n};\n')
