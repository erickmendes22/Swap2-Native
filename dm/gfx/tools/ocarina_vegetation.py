"""Verified static NVN2 supplement; never resplit or modify the working base.

The reviewed manifest supplies source locations AND original stage/partner facts.
Only its three top-level shader containers are read, including two SARC members.
Every extracted control/code hash must match before the translator sees a record.
No runtime capture, guessed layout or replacement of a working shader is needed.
"""
from pathlib import Path
import json
import os
import re
import struct

ROOT = Path(__file__).resolve().parents[3]
TITLE = '0400486024DEC000'
MANIFEST = ROOT / 'dm/games' / TITLE / 'vegetation_shaders.tsv'
HEADER = ROOT / 'dm/gfx/vk_android/vka_vegetation_supplement.h'
JAVA = ROOT / 'android/app/src/ondevice/java/dev/nxnative/android/OcarinaVegetation.java'


def manifest(path=MANIFEST):
    rows = {}
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith('#'): continue
        key, stage, source, raw = line.split('\t')
        facts = json.loads(raw)
        if not re.fullmatch('[0-9a-f]{16}', key) or key in rows or stage not in ('task', 'mesh'):
            raise ValueError('Invalid vegetation shader key/stage')
        if not re.fullmatch(r'/Shader/[^#]+#BNSH@0x[0-9a-f]+#var[0-9]+', source):
            raise ValueError('Invalid vegetation source location')
        if '..' in source.split('/') or not facts.get('pair') or not facts.get('local'):
            raise ValueError('Missing vegetation dependencies')
        layout = facts.get('mesh', [])
        # This supplement deliberately needs no fragment overrides. A future
        # per-primitive interface requires a separately reviewed pixel update.
        if len(layout) < 3 or -1 in layout or stage == 'mesh' and not all(layout[:2]):
            raise ValueError('Unreviewed vegetation mesh/pixel interface')
        if not all(re.fullmatch('[0-9a-f]{16}', k) for k in facts['pair']):
            raise ValueError('Invalid vegetation dependency')
        rows[key] = (stage, source, facts)
    if not rows or len(rows) > 1024: raise ValueError('Invalid vegetation supplement size')
    return rows


def dependencies(rows):
    return {p for _, _, facts in rows.values() for p in facts['pair']}


def header_text(rows=None):
    rows = manifest() if rows is None else rows
    lines = ['// Generated by ocarina_vegetation.py --header; reviewed original NVN2 stages.',
             '#pragma once', '#include <stdint.h>',
             'static const struct { uint64_t key; unsigned stage; } vka_veg_entries[] = {']
    lines += [f'    {{UINT64_C(0x{k}), DMSH_VK_STAGE_{"TS" if v[0] == "task" else "MS"}}},' for k, v in sorted(rows.items())]
    lines += ['};', 'static const uint64_t vka_veg_dependencies[] = {']
    lines += [f'    UINT64_C(0x{k}),' for k in sorted(dependencies(rows))]
    lines += ['};', '']
    return '\n'.join(lines)


def java_text(rows=None):
    rows = manifest() if rows is None else rows
    return '\n'.join([
        '// Generated by ocarina_vegetation.py --header. No native packer in the launcher.',
        'package dev.nxnative.android;', '', 'import java.util.List;', '',
        'final class OcarinaVegetation {', '    private OcarinaVegetation() {}',
        '    static final List<String> KEYS = List.of(',
        ',\n'.join('        "' + k + '"' for k in sorted(rows)),
        '    );', '}', ''])


def extract(romfs, package, rows=None, reader=None):
    """Read only reviewed container/BNSH locations, validate every source.

    The reader and romfs adapter are the production splitter, supporting NUP,
    RomFS images and directories. Group by outer file so it is inflated once.
    """
    if reader is None:
        import shader_split as reader
    # The full splitter initializes these in its worker pool. This bounded
    # extractor does not enter that pool, so importing shader_split alone
    # leaves dictionary 1 unavailable even when it exists in the game dump.
    # An update NUP may keep an unchanged dictionary pack in its base RomFS.
    roots = [romfs]
    nup_path = reader.nup.split(romfs)
    base = None
    if nup_path and nup_path[1].startswith('update/'):
        base = nup_path[0] + ':base/romfs'
    elif not nup_path:
        version = reader.os.path.dirname(reader.os.path.normpath(romfs))
        updates = reader.os.path.dirname(version)
        if (reader.os.path.basename(romfs) == 'romfs'
                and reader.os.path.basename(updates) == 'updates'
                and reader.os.path.basename(version).isdigit()):
            base = reader.os.path.join(reader.os.path.dirname(updates), 'base/romfs')
    if base and reader.os.path.isdir(base): roots.insert(0, base)
    dictionaries = {}
    for root in roots: dictionaries.update(reader.zs_dicts(root))
    previous = reader.ZDICTS, reader._ZD
    reader.ZDICTS, reader._ZD = dictionaries, {}
    print('vegetation zstd dictionaries: ' + ','.join(map(str, sorted(dictionaries)))
          + ' (fresh base/update scope)', flush=True)
    try:
        return _extract(romfs, package, rows, reader)
    finally:
        reader.ZDICTS, reader._ZD = previous


def _extract(romfs, package, rows, reader):
    rows = manifest() if rows is None else rows
    grouped = {}
    for key, (stage, source, facts) in rows.items():
        container, at = source.split('#BNSH@')
        base = int(at.split('#')[0], 16)
        # Only a compressed top-level file and at most one SARC member.
        outer, sep, member = container.lstrip('/').partition('.zs/')
        if sep: outer += '.zs'
        grouped.setdefault(outer, {}).setdefault(member, {}).setdefault(base, set()).add(key)
    package = Path(package); package.mkdir(parents=True, exist_ok=True)
    records = {'task': {}, 'mesh': {}}
    for outer, members in sorted(grouped.items()):
        print('stage: vegetation sources ' + outer, flush=True)
        path = reader.os.path.join(romfs, outer)
        if outer.endswith('.zs'): data = reader.unzs(path)
        else:
            with reader.open(path, 'rb') as f: data = f.read()
        blobs = {'': data} if '' in members else {}
        if any(m for m in members):
            blobs.update((nm, b) for nm, b in reader.sarc_members(data, outer) if nm in members)
        for member, groups in members.items():
            if member not in blobs: raise ValueError('Vegetation SARC member missing: ' + member)
            blob = blobs[member]
            for base, wanted in sorted(groups.items()):
                if blob[base:base+4] != b'BNSH': raise ValueError('Vegetation BNSH source missing')
                found = {}
                for where, st, ctl, code in reader.bnsh_shaders(blob, base, '/' + outer + ('/' + member if member else '')):
                    key = reader.skey(ctl, code)
                    if key not in wanted: continue
                    expected_stage, expected_source, facts = rows[key]
                    if where != expected_source: continue  # another variation can share the same key
                    if st != {'mesh': 'ms', 'task': 'ts'}[expected_stage]:
                        raise ValueError('Vegetation source stage/location mismatch: ' + key)
                    if len(ctl) < 0xd8 or len(code) < 0x80 or reader.check(where, st, ctl, code):
                        raise ValueError('Vegetation source truncated: ' + key)
                    # The static layout must agree with its actual NVN2 bytes.
                    # There are no per-primitive outputs in this reviewed set;
                    # partner source is not needed to infer any missing input.
                    derived = reader.mesh_facts(key, st, ctl, code, {}, set())
                    for field in ('local', 'shared', 'mesh'):
                        expected = facts.get(field)
                        # Pixel-only padding is the reviewed static pair
                        # table's information, not a plane written by NVN2.
                        if field == 'mesh' and -2 in expected:
                            expected = expected[:expected.index(-2)]
                        if derived.get(field) != expected:
                            raise ValueError('Vegetation static fact mismatch: ' + key + ' ' + field)
                    rec = bytearray(b'BTCDBTCD' + bytes(0x30))
                    struct.pack_into('<II', rec, 0x28, len(ctl), len(code)); rec.extend(code); rec.extend(ctl)
                    if rec.find(reader.CTL_MAGIC) != 0x38 + len(code) or rec.count(b'BTCDBTCD') != 1:
                        raise ValueError('Ambiguous vegetation record: ' + key)
                    found[key] = bytes(rec)
                if set(found) != wanted:
                    raise ValueError('Vegetation source keys missing: ' + ','.join(sorted(wanted - set(found))))
                for key, rec in found.items(): records[rows[key][0]][key] = rec
        del blobs, data
    locations = {}
    for stage, items in records.items():
        name = ('ts' if stage == 'task' else 'ms') + '_vegetation.bin'
        with (package / (name + '.tmp')).open('wb') as out:
            for index, (key, record) in enumerate(sorted(items.items())):
                out.write(record); locations[key] = (name, index)
        os.replace(package / (name + '.tmp'), package / name)
    if set(locations) != set(rows): raise ValueError('Vegetation extraction incomplete')
    print(f'vegetation sources: {len(locations)} verified shaders, {len(grouped)} containers; full base untouched', flush=True)
    return locations


def validate_dependencies(rows, available):
    missing = dependencies(rows) - set(rows) - set(available)
    if missing: raise ValueError('Vegetation base dependency missing: ' + ','.join(sorted(missing)))


if __name__ == '__main__':
    import sys
    if sys.argv[1:] == ['--header']:
        HEADER.write_text(header_text()); JAVA.write_text(java_text())
    elif sys.argv[1:] == ['--check']:
        assert HEADER.read_text() == header_text(), 'Regenerate vegetation supplement header'
        assert JAVA.read_text() == java_text(), 'Regenerate launcher vegetation keys'
    else: raise SystemExit('usage: ocarina_vegetation.py --header | --check')
