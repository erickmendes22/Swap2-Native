#!/usr/bin/env python3
# Compiles the mesh emulation's helper passes (memu_setup.comp, memu_dist.comp: GLSL written for vka_memu_abi.h, not game code) to SPIR-V 1.3 with glslangValidator and
# writes them as word arrays into ../vka_memu_helpers_spv.h, which vka_memu.c includes. Run it after changing a pass or vka_memu_abi.h; needs glslangValidator and spirv-val
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("memu_setup.comp", "SPV_MEMU_SETUP"), ("memu_dist.comp", "SPV_MEMU_DIST")]

def main():
    coalesced = "--coalesced" in sys.argv[1:]
    compact = "--compact" in sys.argv[1:]
    out = ["// Generated by dm/gfx/vk_android/memu/spv.py from the GLSL beside it (glslangValidator -V --target-env vulkan1.1 -g0): the mesh emulation's helper passes. Do not edit",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "#pragma once", "#include <stdint.h>"]
    with tempfile.TemporaryDirectory() as tmp:
        for src, name in ([("memu_compact.comp", "SPV_MEMU_COMPACT")] if compact else SHADERS):
            spv = os.path.join(tmp, src + ".spv")
            defines = ["-DVKA_MEMU_ENABLE_COALESCED=1"] if coalesced else []
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-g0", *defines, "-o", spv, os.path.join(HERE, src)], check=True, stdout=subprocess.DEVNULL)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], check=True)
            data = open(spv, "rb").read()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            out.append("static const uint32_t %s[%d] = {" % (name + ("_COALESCED" if coalesced else ""), len(words)))
            for i in range(0, len(words), 12):
                out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 12]) + ",")
            out.append("};")
    target = "vka_memu_compact_spv.h" if compact else "vka_memu_coalesced_helpers_spv.h" if coalesced else "vka_memu_helpers_spv.h"
    open(os.path.join(HERE, "..", target), "w").write("\n".join(out) + "\n")
    return 0

if __name__ == "__main__":
    sys.exit(main())
