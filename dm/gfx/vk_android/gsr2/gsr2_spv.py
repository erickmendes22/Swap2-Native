#!/usr/bin/env python3
"""Compile Qualcomm GSR2 3-pass Vulkan shaders and validate SPIR-V.

The generated header is an APK build artifact, not an NDSR shader-library input:
no re-preparation of Ocarina's 42k shaders is required. All three passes must
compile successfully; never accept partial or stale output.
"""
import argparse
import glob
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parent / "vka_gsr2_spv.h"
PASSPROGS = (
    ("vka_gsr2_convert", "gsr2_convert.comp"),
    ("vka_gsr2_activate", "gsr2_activate.comp"),
    ("vka_gsr2_upscale", "gsr2_upscale.comp"),
)

def tool(name):
    if shutil.which(name):
        return shutil.which(name)
    roots = [os.environ.get("ANDROID_NDK_HOME", "")] + sorted(
        glob.glob(os.path.expanduser("~/android-ndk-*")), reverse=True)
    for root in filter(None, roots):
        for candidate in glob.glob(os.path.join(root, "shader-tools", "*", name)):
            return candidate
    return None

def compile_header():
    glslc, spirv_val = tool("glslc"), tool("spirv-val")
    if not glslc or not spirv_val:
        raise FileNotFoundError("glslc and spirv-val required (NDK shader-tools)")
    arrays = [
        "// Snapdragon GSR2 temporal reconstruction, BSD-3-Clause.",
        "// Source: dm/gfx/vk_android/gsr2/*.comp; license: gsr2/LICENSE.",
        "// Generated by gsr2_spv.py, validated against Vulkan 1.1. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
    ]
    with tempfile.TemporaryDirectory() as temp:
        for sym, filename in PASSPROGS:
            src = HERE / filename
            out = Path(temp) / (sym + ".spv")
            cmd = [glslc, "-O", "--target-env=vulkan1.1", str(src)]
            subprocess.run(cmd + ["-o", str(out)], check=True)
            subprocess.run([spirv_val, "--target-env", "vulkan1.1", str(out)], check=True)
            data = subprocess.run(cmd + ["-mfmt=num", "-o", "-"],
                                  check=True, capture_output=True, text=True).stdout
            if not data.strip():
                raise RuntimeError(f"empty SPIR-V for {filename}")
            arrays += [f"static const uint32_t {sym}[] = {{", data.strip(), "};"]
    return "\n".join(arrays) + "\n"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="verify existing generated header against the GLSL source")
    args = parser.parse_args()
    try:
        content = compile_header()
    except (FileNotFoundError, subprocess.CalledProcessError, RuntimeError) as err:
        print("GSR2 shader compilation: " + str(err), file=sys.stderr)
        return 2
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print("GSR2 embedded shader header is missing/stale", file=sys.stderr)
            return 1
        return 0
    temp = OUTPUT.with_suffix(".h.tmp")
    temp.write_text(content)
    temp.replace(OUTPUT)
    print(f"GSR2: validated 3 passes, generated {OUTPUT.name} ({len(content)//1024} KiB)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
