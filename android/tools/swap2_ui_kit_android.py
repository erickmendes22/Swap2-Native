#!/usr/bin/env python3
# Swap2-Native: the UI kit's art (assets/artwork/swap2-native/ui-kit) as the Android launcher's resources (android/app/src/main/res).
#   icons/*.svg, brand/symbol.svg  → drawable/<name>.xml   VectorDrawables (path / circle / rect / line, the shapes the kit's generator writes; fill and stroke as in the SVG)
#   backgrounds/launcher.png       → drawable-nodpi/s2_launcher_bg.webp   (the launcher's background, drawn center-crop)
#   illustrations/library-folder.png → drawable-nodpi/s2_library_folder.webp (the first-open illustration, drawn fit-center)
# The icons the launcher already names keep their names (ic_back, ic_settings, ...: Ui.java tints them); the rest are s2_ic_<name>.
# Usage: python android/tools/swap2_ui_kit_android.py   (needs Pillow for the two images). Rerun after the kit changes: tools/generate_swap2_ui_kit.py makes the SVGs.
import math, re, sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
KIT = REPO / 'assets/artwork/swap2-native/ui-kit'
RES = REPO / 'android/app/src/main/res'
SVG = '{http://www.w3.org/2000/svg}'
# the launcher's icon names (Ui.java, MainActivity) → the kit icon that takes their place
SAME = {'ic_back': 'back', 'ic_settings': 'settings', 'ic_play': 'play', 'ic_more': 'more', 'ic_chevron': 'chevron-right', 'ic_add': 'folder-open',
        'ic_build': 'refresh'}
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by android/tools/swap2_ui_kit_android.py from the Swap2-Native UI kit ({src}); change the kit, then rerun it -->\n')


def circle(cx, cy, r):
    return f'M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0Z'


def rect(x, y, w, h, rx):
    if not rx: return f'M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}Z'
    rx = min(rx, w / 2, h / 2)
    return (f'M{x + rx:g},{y:g}h{w - 2 * rx:g}a{rx:g},{rx:g} 0 0,1 {rx:g},{rx:g}v{h - 2 * rx:g}a{rx:g},{rx:g} 0 0,1 {-rx:g},{rx:g}'
            f'h{-(w - 2 * rx):g}a{rx:g},{rx:g} 0 0,1 {-rx:g},{-rx:g}v{-(h - 2 * rx):g}a{rx:g},{rx:g} 0 0,1 {rx:g},{-rx:g}Z')


def color(v, opacity=None):
    if not v or v == 'none': return None
    v = v.strip()
    if re.fullmatch(r'#[0-9A-Fa-f]{3}', v): v = '#' + ''.join(ch * 2 for ch in v[1:])
    if not re.fullmatch(r'#[0-9A-Fa-f]{6}', v): raise ValueError(f'color {v}')
    a = '' if opacity is None else f'{round(float(opacity) * 255):02X}'
    return f'#{a}{v[1:].upper()}'


def walk(el, inherited, out):
    st = dict(inherited)
    for k in ('fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity', 'fill-opacity', 'stroke-opacity'):
        if el.get(k) is not None: st[k] = el.get(k)
    tag = el.tag.replace(SVG, '')
    f = lambda k: float(el.get(k, 0))
    d = None
    if tag == 'path': d = el.get('d')
    elif tag == 'circle': d = circle(f('cx'), f('cy'), f('r'))
    elif tag == 'rect': d = rect(f('x'), f('y'), f('width'), f('height'), float(el.get('rx', el.get('ry', 0))))
    elif tag == 'line': d = f'M{f("x1"):g},{f("y1"):g}L{f("x2"):g},{f("y2"):g}'
    elif tag in ('svg', 'g'): pass
    else: raise ValueError(f'unsupported SVG element <{tag}>')
    if d:
        a = [f'android:pathData="{d}"']
        fill = color(st.get('fill', '#000000'), st.get('fill-opacity') or st.get('opacity'))
        stroke = color(st.get('stroke'), st.get('stroke-opacity') or st.get('opacity'))
        if fill: a.append(f'android:fillColor="{fill}"')
        if stroke:
            a += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{float(st.get("stroke-width", 1)):g}"']
            if st.get('stroke-linecap'): a.append(f'android:strokeLineCap="{st["stroke-linecap"]}"')
            if st.get('stroke-linejoin'): a.append(f'android:strokeLineJoin="{st["stroke-linejoin"]}"')
        out.append('    <path ' + '\n        '.join(a) + ' />')
    for ch in el: walk(ch, st, out)


def vector(svg, size_dp=None):
    root = ET.parse(svg).getroot()
    vb = [float(x) for x in root.get('viewBox').replace(',', ' ').split()]
    w, h = vb[2], vb[3]
    paths = []
    walk(root, {}, paths)
    dw = size_dp or w
    dh = dw * h / w
    return (HEAD.format(src=svg.relative_to(REPO).as_posix()) +
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="{dw:g}dp" android:height="{dh:g}dp"\n'
            f'    android:viewportWidth="{w:g}" android:viewportHeight="{h:g}">\n' + '\n'.join(paths) + '\n</vector>\n')


def main():
    drawable = RES / 'drawable'
    made = []
    for name, src in SAME.items():
        (drawable / f'{name}.xml').write_text(vector(KIT / f'icons/{src}.svg', 24), encoding='utf-8', newline='\n'); made.append(name)
    for svg in sorted((KIT / 'icons').glob('*.svg')):
        n = 's2_ic_' + svg.stem.replace('-', '_')
        (drawable / f'{n}.xml').write_text(vector(svg, 24), encoding='utf-8', newline='\n'); made.append(n)
    (drawable / 's2_symbol.xml').write_text(vector(KIT / 'brand/symbol.svg', 40), encoding='utf-8', newline='\n'); made.append('s2_symbol')
    try: from PIL import Image
    except ImportError: sys.exit('[RED] Pillow is needed for the background and the illustration (python -m pip install pillow)')
    nodpi = RES / 'drawable-nodpi'; nodpi.mkdir(exist_ok=True)
    # The background is drawn center-crop behind the launcher: 1672x941 as the kit gives it, a lossy WebP (it has no text or edges to blur)
    Image.open(KIT / 'backgrounds/launcher.png').convert('RGB').save(nodpi / 's2_launcher_bg.webp', 'WEBP', quality=82, method=6)
    # The illustration is drawn at most ~220 dp wide (xxxhdpi: 880 px): 900 px keeps it sharp; lossless keeps its alpha edge clean
    ill = Image.open(KIT / 'illustrations/library-folder.png').convert('RGBA')
    ill.resize((900, 900), Image.LANCZOS).save(nodpi / 's2_library_folder.webp', 'WEBP', lossless=True, method=6)
    made += ['s2_launcher_bg', 's2_library_folder']
    print(f'{len(made)} resources: {" ".join(made)}')


if __name__ == '__main__':
    main()
